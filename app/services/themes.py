_THEMES_BY_SLUG: dict[str, Theme] = {theme.slug: theme for theme in THEMES}


def get_theme(slug: str) -> Theme | None:
    return _THEMES_BY_SLUG.get(slug.lower())


def theme_summaries() -> list[ThemeSummary]:
    return [
        ThemeSummary(
            slug=theme.slug,
            name=theme.name,
            description=theme.description,
            ticker_count=len(theme.tickers),
        )
        for theme in THEMES
    ]


async def build_theme_detail(theme: Theme, finnhub) -> ThemeDetailResponse:
    """Static list + live quotes/industries; every failure degrades to a warning."""
    warnings: list[str] = []
    quote_results = await asyncio.gather(
        *(finnhub.get_quote(t) for t in theme.tickers), return_exceptions=True
    )
    quotes: dict[str, Quote] = {}
    for ticker, result in zip(theme.tickers, quote_results):
        if isinstance(result, Quote):
            quotes[ticker] = result
            continue
        if not isinstance(result, FinnhubError):
            raise result
        warnings.append(f"quote_unavailable:{ticker}")

    sectors = await _fetch_sectors(finnhub, theme.tickers, warnings)

    stocks = [
        ThemeStock(
            ticker=ticker,
            price=quotes[ticker].current_price if ticker in quotes else None,
            percent_change=quotes[ticker].percent_change if ticker in quotes else None,
            industry=sectors.get(ticker),
            price_status="ok" if ticker in quotes else "unavailable",
        )
        for ticker in theme.tickers
    ]
    return ThemeDetailResponse(
        slug=theme.slug,
        name=theme.name,
        description=theme.description,
        stocks=stocks,
        warnings=warnings,
        disclaimer=STATISTICAL_DISCLAIMER,
    )
